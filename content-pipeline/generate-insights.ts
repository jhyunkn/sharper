/**
 * Insight generation pipeline — run from Claude Code session.
 * Reads user profiles from Supabase, generates personal daily insights,
 * writes them back. No Anthropic API key needed — Claude generates inline.
 *
 * Usage:
 *   npx tsx generate-insights.ts              -- all users
 *   npx tsx generate-insights.ts --user <id>  -- single user
 *   npx tsx generate-insights.ts --preview    -- print without saving
 */

import 'dotenv/config';
import { createClient } from '@supabase/supabase-js';
import { createHash } from 'crypto';

const supabase = createClient(
  process.env.SUPABASE_URL!,
  process.env.SUPABASE_SERVICE_KEY!
);

interface UserRow {
  id: string;
  display_name: string;
  archetype: string;
  saved_card_ids: string[];
  viewed_card_ids: string[];
}

interface CardRow {
  id: string;
  author: string;
  domain: string;
  themes: string[];
  archetype_affinity: string[];
}

interface InsightPayload {
  user_id: string;
  archetype_id: string;
  signal: string;
  mindset: string;
  dos: string[];
  donts: string[];
  top_themes: string[];
  top_domains: string[];
  top_authors: string[];
  profile_hash: string;
  generated_at: string;
}

function profileHash(saved: string[], archetype: string): string {
  return createHash('sha1').update(archetype + saved.slice(0, 20).join('')).digest('hex').slice(0, 12);
}

function buildProfile(user: UserRow, cards: CardRow[]) {
  const saved = cards.filter(c => user.saved_card_ids.includes(c.id));

  const themeCounts: Record<string, number> = {};
  const domainCounts: Record<string, number> = {};
  const authorCounts: Record<string, number> = {};

  for (const c of saved) {
    for (const t of c.themes) themeCounts[t] = (themeCounts[t] || 0) + 1;
    domainCounts[c.domain] = (domainCounts[c.domain] || 0) + 1;
    authorCounts[c.author] = (authorCounts[c.author] || 0) + 1;
  }

  const topThemes = Object.entries(themeCounts).sort((a, b) => b[1] - a[1]).slice(0, 5).map(e => e[0]);
  const topDomains = Object.entries(domainCounts).sort((a, b) => b[1] - a[1]).slice(0, 3).map(e => e[0]);
  const topAuthors = Object.entries(authorCounts).sort((a, b) => b[1] - a[1]).slice(0, 4).map(e => e[0]);

  return { topThemes, topDomains, topAuthors, savedCount: saved.length };
}

