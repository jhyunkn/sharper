async function main() {
  const args = process.argv.slice(2);
  const userFilter = args.includes('--user') ? args[args.indexOf('--user') + 1] : null;
  const preview = args.includes('--preview');

  // Load all user profiles
  const { data: users, error: usersErr } = await supabase
    .from('user_profiles')
    .select('id, display_name, archetype, saved_card_ids, viewed_card_ids')
    .not('archetype', 'is', null);

  if (usersErr || !users?.length) {
    console.log('No user profiles found in Supabase yet.');
    console.log('Users sync to Supabase when they save cards in the app.');
    return;
  }

  const targets = userFilter ? users.filter((u: UserRow) => u.id === userFilter) : users;
  console.log(`Generating insights for ${targets.length} user(s)...`);

  // Load all relevant cards
  const allSavedIds = [...new Set(targets.flatMap((u: UserRow) => u.saved_card_ids || []))];
  const { data: cards } = await supabase
    .from('specimen_cards')
    .select('id, author, domain, themes, archetype_affinity')
    .in('id', allSavedIds.length ? allSavedIds : ['__none__']);

  const cardList: CardRow[] = cards || [];

  const insights: InsightPayload[] = [];

  for (const user of targets as UserRow[]) {
    const { topThemes, topDomains, topAuthors, savedCount } = buildProfile(user, cardList);
    const hash = profileHash(user.saved_card_ids || [], user.archetype);

    const { signal, mindset, dos, donts } = generateInsight(user, topThemes, topDomains, topAuthors, savedCount);

    const insight: InsightPayload = {
      user_id: user.id,
      archetype_id: user.archetype,
      signal,
      mindset,
      dos,
      donts,
      top_themes: topThemes,
      top_domains: topDomains,
      top_authors: topAuthors,
      profile_hash: hash,
      generated_at: new Date().toISOString(),
    };

    insights.push(insight);
    console.log(`\n── ${user.display_name} (${user.archetype}) ──`);
    console.log(`Signal: ${signal}`);
    console.log(`Themes: ${topThemes.join(', ')}`);
    console.log(`Authors: ${topAuthors.join(', ')}`);
    if (preview) {
      console.log(`\nMindset:\n${mindset}`);
      console.log(`\nDo: ${dos.join(' | ')}`);
      console.log(`Don't: ${donts.join(' | ')}`);
    }
  }

  if (preview) { console.log('\nPreview only — nothing saved.'); return; }

  const { error } = await supabase.from('user_insights').upsert(insights, { onConflict: 'user_id' });
  if (error) { console.error('Error saving insights:', error.message); return; }

  console.log(`\n✓ ${insights.length} insight(s) written to Supabase.`);
}

main().catch(console.error);
